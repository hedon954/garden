export function plannedFiles() {
  const files = new Map();
  files.set(path.join(PREVIEW_DIR, ".gitkeep"), "");
  for (const item of DIAGRAM_RECIPES) {
    files.set(path.join(PREVIEW_DIR, `${item.name}.svg`), `${previewSvgMarkup(item)}\n`);
  }
  files.set(ZH_INDEX, zhIndex());
  files.set(EN_INDEX, enIndex());
  DIAGRAM_RECIPES.forEach((item, index) => {
    const order = (index + 1) * 10 + 1;
    files.set(path.join(ZH_DIR, `${item.name}.md`), zhPage(item, order));
    files.set(path.join(EN_DIR, `${item.name}.md`), enPage(item, order));
  });
  return files;
}

export function checkGenerated(root = ROOT) {
  const issues = [];
  const files = plannedFiles();
  for (const [file, body] of files) {
    if (file.endsWith(".gitkeep") && !body) continue;
    const rel = path.relative(ROOT, file).split(path.sep).join("/");
    const actualPath = path.join(root, rel);
    if (!fs.existsSync(actualPath)) {
      issues.push({ file: rel, message: "missing generated handbook file; run node scripts/handbook-diagrams.mjs" });
      continue;
    }
    const actual = fs.readFileSync(actualPath, "utf8");
    if (actual !== body) {
      issues.push({ file: rel, message: "generated handbook file is stale; run node scripts/handbook-diagrams.mjs" });
    }
  }
  for (const file of STALE_FILES) {
    const rel = path.relative(ROOT, file).split(path.sep).join("/");
    const actualPath = path.join(root, rel);
    if (fs.existsSync(actualPath)) {
      issues.push({ file: rel, message: "stale generated handbook file should be removed; run node scripts/handbook-diagrams.mjs" });
    }
  }
  return issues;
}

export function writeGenerated() {
  fs.mkdirSync(PREVIEW_DIR, { recursive: true });
  fs.mkdirSync(ZH_DIR, { recursive: true });
  fs.mkdirSync(EN_DIR, { recursive: true });
  for (const [file, body] of plannedFiles()) {
    if (file.endsWith(".gitkeep") && !body) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
  }
  for (const file of STALE_FILES) {
    if (fs.existsSync(file)) fs.rmSync(file);
  }
}

const isCli = path.basename(process.argv[1] ?? "") === "handbook-diagrams.mjs";
if (isCli) {
  const check = process.argv.includes("--check");
  if (check) {
    const issues = checkGenerated();
    if (issues.length) {
      for (const issue of issues) process.stderr.write(`${issue.file}: ${issue.message}\n`);
      process.exitCode = 1;
    }
  } else {
    writeGenerated();
    process.stdout.write(`Wrote ${DIAGRAM_RECIPES.length} figure pages and previews from diagram-recipes.\n`);
  }
}
